interface QuickNoteSeed {
  topicId: string;
  sixtySecondSummary: string[];
  coreConcept: string;
  essentialFacts: string[];
  highYieldSequence: string[];
  memoryAid: string;
  definitions: Array<{ term: string; definition: string }>;
  classifications: Array<{ title: string; items: string[] }>;
  mechanismSteps: string[];
  importantRelationships: string[];
  comparisonTable?: { title: string; headers: string[]; rows: string[][] };
  diagramCaptions: Array<{ title: string; description: string }>;
  clinicalCorrelations: string[];
  commonMistakes: string[];
  rapidRevisionSummary: string[];
  refs: MedicalReference[];
}

function buildNote(s: QuickNoteSeed): MBBSNoteSection {
  return {
    topicId: s.topicId,
    version: '1.1.0',
    status: 'published',
    author: 'MedVerse Editorial Pipeline',
    reviewer: 'NMC CBME Reference Alignment',
    lastReviewedAt: '2026-11-28',
    sixtySecondSummary: s.sixtySecondSummary,
    twoMinuteRevision: {
      coreConcept: s.coreConcept,
      essentialFacts: s.essentialFacts,
      highYieldSequence: s.highYieldSequence,
      memoryAid: s.memoryAid,
    },
    detailedNotes: {
      coreConcept: s.coreConcept,
      definitions: s.definitions,
      classifications: s.classifications,
      mechanismSteps: s.mechanismSteps,
      importantRelationships: s.importantRelationships,
      comparisonTable: s.comparisonTable,
      diagramCaptions: s.diagramCaptions,
      clinicalCorrelations: s.clinicalCorrelations,
      commonMistakes: s.commonMistakes,
      rapidRevisionSummary: s.rapidRevisionSummary,
    },
    references: s.refs,
  };
}

