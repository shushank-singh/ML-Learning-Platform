function makeTopics(chapterId: string, titles: { title: string; scope?: 'main_and_advanced' | 'jee_main_only' | 'jee_advanced_only'; lessons: { id: string; title?: string }[] }[]) {
  return titles.map((t, idx) => ({
    id: `${chapterId}-t${idx + 1}`,
    title: t.title,
    examScope: t.scope || ('main_and_advanced' as const),
    lessonIds: t.lessons.map((l) => l.id),
  }));
}

